#[test]
fn parser_rejects_bad_metadata_backwards_layers_and_segment_budget() {
    let good = "G90\nM83\nG1Z.4\n;WIDTH:0.42\nG1X10E.4\n";
    for bad in [
        ";HEIGHT:NaN",
        ";HEIGHT:0",
        ";WIDTH:NaN",
        ";WIDTH:0.1\nG1X20E.4",
        "G1Z.2\nG1X20E.4",
        "G1E1e999",
    ] {
        assert!(parse(&format!("{good}{bad}")).is_err(), "accepted {bad}");
    }
    let mut text = String::from("G91\nM83\nG1Z.2\n;WIDTH:0.42\n");
    text.push_str(&"G1X1E.04\n".repeat(turninator::print::beads::MAX_BEAD_SEGMENTS + 1));
    assert!(parse(&text).unwrap_err().to_string().contains("budget"));
}

#[test]
fn prusa_startup_loads_model_layers_without_the_purge_line() {
    let data = parse("; generated by Slic3r Prusa Edition 1.40.1+win64\nM115 U3.2.1\nM201 X1000 Y1000 Z200 E5000\nM203 X200 Y200 Z12 E120\nM204 S1250 T1250\nM205 X10 Y10 Z0.4 E2.5\nM83\nG28 W\nG80\nG1 Y-3 F1000\nG92 E0\nG1 X60 E9\nG1 X100 E12.5\nG92 E0\nM221 S95\nM900 K45\nG21\nG90\nM83\n;BEFORE_LAYER_CHANGE\nG1 E-.8\nG1 Z.6\nG1 X10 Y10\nG1 Z.2\nG1 E.8\nG1 X20 E.4\n;BEFORE_LAYER_CHANGE\nG1 Z.5\nG1 X30 E.6\nM84\n").unwrap();
    assert_eq!(data.segments.len(), 2);
    near(data.segments[0].start[0], 10.);
    near(data.segments[0].height_mm, 0.2);
    near(data.segments[1].height_mm, 0.3);
    near(
        data.segments[0].volume_mm3,
        0.4 * 0.95 * std::f64::consts::PI * 1.75f64.powi(2) / 4.,
    );
    assert!(data.warnings.iter().any(|w| w.contains("purge")));
    let home = ParseOptions {
        homing_position_mm: Some([0.; 3]),
        ..Default::default()
    };
    let data=parse_gcode("; generated by Slic3r Prusa Edition 1.40.1+win64\nG28 W\nG80\nG28 W\nM83\n;BEFORE_LAYER_CHANGE\nG1 X10 Y10 Z.2\nG1 X20 E.4",&home).unwrap();
    assert_eq!(data.segments.len(), 1);
}

