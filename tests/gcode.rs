#[test]
fn kisslicer_motor_extrusion_uses_reported_filament_speed_and_layer_thickness() {
    let text = "; KISSlicer - FREE\nG21\nG90\nG28\n; BEGIN_LAYER_OBJECT z=0.2 z_thickness=0.2\nM542\nM551 P32000 S900\nM543\nG1 X10 Y10 Z.2 F1200\nM227 S2963 P2963\nM108 S0\nM101\n; head speed 20.000000, filament speed 0.600000, preload 0.000000\nM108 S500\n; 'Perimeter Path', 50.0 [RPM], 20.0 [head mm/s]\nG1 X20 Y10 Z.2 F1200\nM103\nG1 X30 Y10 Z.2\nM542\nM561 P6400 S900\nM543\n";
    let data = parse(text).unwrap();
    assert_eq!(data.segments.len(), 1);
    near(
        data.segments[0].volume_mm3,
        0.3 * std::f64::consts::PI * 1.75f64.powi(2) / 4.,
    );
    assert_eq!(data.segments[0].feature, "Perimeter Path");
    assert!(data.warnings.iter().any(|w| w.contains("KISSlicer")));
    assert!(
        parse(&text.replace(
            "; head speed 20.000000, filament speed 0.600000, preload 0.000000\n",
            ""
        ))
        .is_err()
    );
    assert!(parse(&text.replace("M227 S2963 P2963", "M227 S3000 P2963")).is_err());
    let changed = parse(&text.replace(
        "G1 X20 Y10 Z.2 F1200",
        "G1 X20 Y10 Z.2 F1200\nM108 S1000\nG1 X25 Y10 Z.2 F1200",
    ))
    .unwrap();
    assert_eq!(changed.segments.len(), 2);
    near(
        changed.segments[0].volume_mm3,
        changed.segments[1].volume_mm3,
    );
    assert!(
        parse_gcode(
            &text.replace("G1 X20 Y10 Z.2 F1200", "G2 X20 Y10 I5 J0"),
            &ParseOptions {
                allow_arcs: true,
                ..Default::default()
            }
        )
        .is_err()
    );
}

