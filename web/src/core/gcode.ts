// G-code interpreter: turns planar FFF G-code into extrusion bead segments.
//
// Conventions (final-plan.md): XYZ/E absolute/relative modes are tracked
// separately (G90/G91 set both, M82/M83 set E only). Retractions create an
// extrusion debt that positive E repays before material is deposited; E-only
// moves and travel never create beads. The bead top sits at nozzle Z, so a
// bead of height h is centred at Z - h/2. Cross-section is a stadium of width
// w and height h with area h*(w - h) + pi*h^2/4; width comes from ;WIDTH:
// metadata when present, otherwise from deposited volume per length.

export const MAX_SEGMENTS = 6_000_000;

export interface Toolpath {
  count: number;
  /** Bead centreline endpoints (mm), 3 floats each, build frame. */
  start: Float32Array;
  end: Float32Array;
  width: Float32Array;
  height: Float32Array;
  layer: Uint32Array;
  feature: Uint8Array;
  tool: Uint8Array;
  /** Top Z of each layer (mm, build frame). */
  layerZ: number[];
  /** Feature names indexed by feature id. */
  features: string[];
  /** Translation applied to bring the print to the build frame. */
  shift: [number, number, number];
  min: [number, number, number];
  max: [number, number, number];
  stats: {
    lines: number;
    beads: number;
    filamentMm: number;
    volumeMm3: number;
    slicer: string | null;
    filamentDiameter: number;
    widthFromVolume: number;
    clampedWidths: number;
    arcs: number;
    tools: number;
  };
  warnings: string[];
}

export class GcodeError extends Error {}

export interface GcodeOptions {
  filamentDiameter?: number;
  /** Used when neither ;HEIGHT: nor layer spacing defines a height. */
  defaultLayerHeight?: number;
}

function headerNumber(text: string, key: string): number | null {
  const m = new RegExp(`^;\\s*${key}\\s*[=:]\\s*([0-9.]+)`, 'm').exec(text);
  return m ? Number(m[1]) : null;
}

/** Normalise slicer feature names to a small shared vocabulary. */
export function normaliseFeature(raw: string): string {
  const s = raw.trim().toLowerCase();
  if (/outer wall|external perimeter|wall-outer|outer-wall/.test(s)) return 'Outer wall';
  if (/inner wall|^perimeter|wall-inner|inner-wall/.test(s)) return 'Inner wall';
  if (/overhang/.test(s)) return 'Overhang wall';
  if (/top (solid )?(infill|surface)|^top$|ironing/.test(s)) return 'Top surface';
  if (/bottom (solid )?(infill|surface)|^bottom$/.test(s)) return 'Bottom surface';
  if (/bridge/.test(s)) return 'Bridge';
  if (/solid infill|^skin$/.test(s)) return 'Solid infill';
  if (/gap fill/.test(s)) return 'Gap fill';
  if (/support interface|support-interface/.test(s)) return 'Support interface';
  if (/support/.test(s)) return 'Support';
  if (/skirt|brim/.test(s)) return 'Skirt/Brim';
  if (/wipe|prime tower|purge/.test(s)) return 'Wipe tower';
  if (/infill|fill$/.test(s)) return 'Sparse infill';
  if (/custom/.test(s)) return 'Custom';
  return raw.trim() || 'Unknown';
}

/** Features hidden by default because they are not part of the printed part. */
export const AUXILIARY_FEATURES = new Set(['Skirt/Brim', 'Wipe tower', 'Custom']);

class SegmentBuffer {
  s: number[] = []; e: number[] = []; w: number[] = []; h: number[] = [];
  layer: number[] = []; feature: number[] = []; tool: number[] = [];
  get length() { return this.w.length; }
}

export function parseGcode(text: string, opts: GcodeOptions = {}): Toolpath {
  const warnings: string[] = [];
  const filamentDiameter = opts.filamentDiameter ?? headerNumber(text, 'filament_diameter') ?? 1.75;
  const filamentArea = Math.PI * (filamentDiameter / 2) ** 2;
  const slicer = /generated by\s+([A-Za-z][\w.\- ]*?\s[\d.]+)/i.exec(text.slice(0, 4000))?.[1] ?? null;

  // Machine state.
  let x = 0, y = 0, z = 0, e = 0;
  let absXYZ = true, absE = true, inches = false;
  let debt = 0;
  let tool = 0;
  let tools = 1;
  // Annotation state.
  let featureName = 'Unknown';
  let metaWidth: number | null = null;
  let metaHeight: number | null = null;
  // Layering.
  let layerTop = -Infinity;
  let layerIndex = -1;
  let layerHeight = 0;
  const layerZ: number[] = [];
  const featureIds = new Map<string, number>();
  const features: string[] = [];
  const featureId = (name: string) => {
    let id = featureIds.get(name);
    if (id === undefined) {
      id = features.length;
      if (id > 250) return 250;
      featureIds.set(name, id);
      features.push(name);
    }
    return id;
  };

  const buf = new SegmentBuffer();
  let widthFromVolume = 0, clamped = 0, arcs = 0, filamentMm = 0, volume = 0;

  const deposit = (x0: number, y0: number, x1: number, y1: number, zTop: number, dE: number) => {
    const len = Math.hypot(x1 - x0, y1 - y0);
    if (len < 1e-6) return;
    // Layer bookkeeping on extruding moves only (ignores Z-hops/travel).
    if (zTop > layerTop + 1e-4) {
      layerHeight = metaHeight ?? (layerIndex < 0 ? zTop : zTop - layerTop);
      if (!(layerHeight > 0.005)) layerHeight = opts.defaultLayerHeight ?? 0.2;
      layerTop = zTop;
      layerIndex++;
      layerZ.push(zTop);
    }
    const h = metaHeight ?? layerHeight;
    const vol = dE * filamentArea;
    let w: number;
    if (metaWidth !== null) {
      w = metaWidth;
    } else {
      widthFromVolume++;
      const area = vol / len;
      w = (area - (Math.PI * h * h) / 4) / h + h;
    }
    if (!(w >= h)) { w = h; clamped++; }
    if (buf.length >= MAX_SEGMENTS) throw new GcodeError(`More than ${MAX_SEGMENTS.toLocaleString()} extrusion segments`);
    buf.s.push(x0, y0, zTop - h / 2);
    buf.e.push(x1, y1, zTop - h / 2);
    buf.w.push(w); buf.h.push(h);
    buf.layer.push(layerIndex); buf.feature.push(featureId(featureName)); buf.tool.push(tool);
    filamentMm += dE;
    volume += vol;
  };

  /** Apply an extrusion amount through the retraction debt; returns net deposit. */
  const settle = (dE: number): number => {
    if (dE < 0) { debt -= dE; return 0; }
    const repay = Math.min(debt, dE);
    debt -= repay;
    return dE - repay;
  };

  const lines = text.split('\n');
  for (let li = 0; li < lines.length; li++) {
    let line = lines[li];
    const sc = line.indexOf(';');
    if (sc >= 0) {
      const c = line.slice(sc + 1).trim();
      if (c.startsWith('TYPE:')) featureName = normaliseFeature(c.slice(5));
      else if (c.startsWith('FEATURE:')) featureName = normaliseFeature(c.slice(8));
      else if (c.startsWith('WIDTH:')) metaWidth = Number(c.slice(6)) || null;
      else if (c.startsWith('HEIGHT:')) metaHeight = Number(c.slice(7)) || null;
      line = line.slice(0, sc);
    }
    line = line.trim();
    if (!line) continue;
    const cmd = line.match(/^([GMT])(\d+)(?:\.\d+)?/i);
    if (!cmd) continue;
    const letter = cmd[1].toUpperCase();
    const num = Number(cmd[2]);
    if (letter === 'T') {
      tool = Math.min(num, 31);
      tools = Math.max(tools, tool + 1);
      continue;
    }
    // Parameter words (compact forms like G1X10Y5E.2 are allowed).
    const words: Record<string, number> = {};
    const re = /([A-Z])\s*([-+]?(?:\d+\.?\d*|\.\d+))/gi;
    re.lastIndex = cmd[0].length;
    let m: RegExpExecArray | null;
    while ((m = re.exec(line)) !== null) words[m[1].toUpperCase()] = Number(m[2]);
    const k = inches ? 25.4 : 1;

    if (letter === 'G' && (num === 0 || num === 1)) {
      const nx = 'X' in words ? (absXYZ ? words.X * k : x + words.X * k) : x;
      const ny = 'Y' in words ? (absXYZ ? words.Y * k : y + words.Y * k) : y;
      const nz = 'Z' in words ? (absXYZ ? words.Z * k : z + words.Z * k) : z;
      let dE = 0;
      if ('E' in words) {
        const ev = words.E * k;
        dE = absE ? ev - e : ev;
        e = absE ? ev : e + ev;
      }
      const net = settle(dE);
      if (net > 0 && num === 1) deposit(x, y, nx, ny, Math.max(z, nz), net);
      x = nx; y = ny; z = nz;
    } else if (letter === 'G' && (num === 2 || num === 3)) {
      arcs++;
      const nx = 'X' in words ? (absXYZ ? words.X * k : x + words.X * k) : x;
      const ny = 'Y' in words ? (absXYZ ? words.Y * k : y + words.Y * k) : y;
      const nz = 'Z' in words ? (absXYZ ? words.Z * k : z + words.Z * k) : z;
      let dE = 0;
      if ('E' in words) {
        const ev = words.E * k;
        dE = absE ? ev - e : ev;
        e = absE ? ev : e + ev;
      }
      let cx: number, cy: number;
      if ('I' in words || 'J' in words) {
        cx = x + (words.I ?? 0) * k;
        cy = y + (words.J ?? 0) * k;
      } else if ('R' in words) {
        const r = words.R * k;
        const mx = (x + nx) / 2, my = (y + ny) / 2;
        const dx = nx - x, dy = ny - y;
        const d = Math.hypot(dx, dy);
        const hh = Math.sqrt(Math.max(0, r * r - (d / 2) ** 2));
        const sgn = (num === 2) === r > 0 ? -1 : 1;
        cx = mx + (sgn * hh * -dy) / d;
        cy = my + (sgn * hh * dx) / d;
      } else {
        warnings.push(`Line ${li + 1}: arc without I/J or R ignored`);
        x = nx; y = ny; z = nz;
        continue;
      }
      const a0 = Math.atan2(y - cy, x - cx);
      let a1 = Math.atan2(ny - cy, nx - cx);
      const cw = num === 2;
      if (cw && a1 >= a0) a1 -= Math.PI * 2;
      if (!cw && a1 <= a0) a1 += Math.PI * 2;
      if (Math.hypot(nx - x, ny - y) < 1e-9) a1 = a0 + (cw ? -Math.PI * 2 : Math.PI * 2); // full circle
      const r = Math.hypot(x - cx, y - cy);
      const sweep = Math.abs(a1 - a0);
      const steps = Math.max(1, Math.ceil(Math.max(sweep / (Math.PI / 18), (sweep * r) / 0.5)));
      const net = settle(dE);
      let px = x, py = y;
      for (let s = 1; s <= steps; s++) {
        const a = a0 + ((a1 - a0) * s) / steps;
        const qx = s === steps ? nx : cx + r * Math.cos(a);
        const qy = s === steps ? ny : cy + r * Math.sin(a);
        if (net > 0) deposit(px, py, qx, qy, Math.max(z, nz), net / steps);
        px = qx; py = qy;
      }
      x = nx; y = ny; z = nz;
    } else if (letter === 'G' && num === 90) { absXYZ = true; absE = true; }
    else if (letter === 'G' && num === 91) { absXYZ = false; absE = false; }
    else if (letter === 'M' && num === 82) absE = true;
    else if (letter === 'M' && num === 83) absE = false;
    else if (letter === 'G' && num === 20) inches = true;
    else if (letter === 'G' && num === 21) inches = false;
    else if (letter === 'G' && num === 92) {
      if ('X' in words) x = words.X * k;
      if ('Y' in words) y = words.Y * k;
      if ('Z' in words) z = words.Z * k;
      if ('E' in words) e = words.E * k;
      if (Object.keys(words).length === 0) { x = y = z = e = 0; }
    } else if (letter === 'G' && num === 28) {
      // Homing: positions become machine zero for the homed axes.
      if (!('X' in words) && !('Y' in words) && !('Z' in words)) { x = y = z = 0; }
      else { if ('X' in words) x = 0; if ('Y' in words) y = 0; if ('Z' in words) z = 0; }
    }
    // G10/G11 (firmware retract) deposit nothing and leave E untouched.
  }

  const n = buf.length;
  if (n === 0) throw new GcodeError('No extrusion moves found');

  // Bounds of the printed part (skirt/brim/purge excluded when anything else
  // exists), then shift into the build frame.
  const aux = new Set(features.map((f, i) => (AUXILIARY_FEATURES.has(f) ? i : -1)).filter((i) => i >= 0));
  const partOnly = buf.feature.some((f) => !aux.has(f));
  let minX = Infinity, minY = Infinity, minZ = Infinity, maxX = -Infinity, maxY = -Infinity, maxZ = -Infinity;
  for (let i = 0; i < n; i++) {
    if (partOnly && aux.has(buf.feature[i])) continue;
    const r = buf.w[i] / 2, hh = buf.h[i] / 2;
    for (const p of [buf.s, buf.e]) {
      minX = Math.min(minX, p[i * 3] - r); maxX = Math.max(maxX, p[i * 3] + r);
      minY = Math.min(minY, p[i * 3 + 1] - r); maxY = Math.max(maxY, p[i * 3 + 1] + r);
      minZ = Math.min(minZ, p[i * 3 + 2] - hh); maxZ = Math.max(maxZ, p[i * 3 + 2] + hh);
    }
  }
  const shift: [number, number, number] = [-(minX + maxX) / 2, -(minY + maxY) / 2, -minZ];
  const start = new Float32Array(n * 3), end = new Float32Array(n * 3);
  for (let i = 0; i < n * 3; i++) {
    start[i] = buf.s[i] + shift[i % 3];
    end[i] = buf.e[i] + shift[i % 3];
  }
  if (clamped > 0) warnings.push(`${clamped} segment(s) had less volume than a ${'w >= h'} bead; drawn at minimum width`);

  return {
    count: n,
    start,
    end,
    width: Float32Array.from(buf.w),
    height: Float32Array.from(buf.h),
    layer: Uint32Array.from(buf.layer),
    feature: Uint8Array.from(buf.feature),
    tool: Uint8Array.from(buf.tool),
    layerZ: layerZ.map((v) => v + shift[2]),
    features,
    shift,
    min: [minX + shift[0], minY + shift[1], 0],
    max: [maxX + shift[0], maxY + shift[1], maxZ + shift[2]],
    stats: {
      lines: lines.length,
      beads: n,
      filamentMm,
      volumeMm3: volume,
      slicer,
      filamentDiameter,
      widthFromVolume,
      clampedWidths: clamped,
      arcs,
      tools,
    },
    warnings,
  };
}
