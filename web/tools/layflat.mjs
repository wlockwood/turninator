// Lay-flat check: Auto lay flat, then click-pick a face for the display pose.
import { chromium } from 'playwright';
import { resolve } from 'node:path';
const stl = resolve(process.argv[2] ?? '../test-models/Amcrest IP5m Camera Mount.stl');
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=d3d11'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 950 } });
const logs = [];
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:5199/');
await page.setInputFiles('input[type=file]', stl);
await page.waitForFunction(() => /triangles/.test(document.querySelector('.status')?.textContent ?? ''));
const canvas = page.locator('canvas[data-testid=viewport]');
await page.getByRole('button', { name: 'Iso', exact: true }).click();
await page.waitForTimeout(300);
await canvas.screenshot({ path: 'test-results/layflat-0.png' });
await page.getByRole('button', { name: 'Auto', exact: true }).click();
await page.waitForFunction(() => /Laid flat|No flat/.test(document.querySelector('.status')?.textContent ?? ''));
console.log(await page.textContent('.status'));
await page.getByRole('button', { name: 'Iso', exact: true }).click();
await page.waitForTimeout(400);
await canvas.screenshot({ path: 'test-results/layflat-1-auto.png' });
await page.getByRole('button', { name: 'Pick (display)' }).click();
const box = await canvas.boundingBox();
await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.45);
await page.waitForTimeout(400);
await page.getByRole('button', { name: 'Iso', exact: true }).click();
await page.waitForTimeout(400);
await canvas.screenshot({ path: 'test-results/layflat-2-pick.png' });
console.log(logs.join('\n') || 'no errors');
await browser.close();
