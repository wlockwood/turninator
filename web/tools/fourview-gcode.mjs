import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const file = resolve(process.argv[2] ?? 'test-results/gcode/Deck_Post_Jig.gcode');
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=d3d11'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 950 } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
await page.goto('http://localhost:5199/');
await page.setInputFiles('input[type=file]', file);
await page.waitForFunction(() => /beads/.test(document.querySelector('.status')?.textContent ?? ''));
await page.click('role=tab[name="Four-view"]');
await page.selectOption('#fvsize', '2048');
const t = Date.now();
await page.click('text=Render four-view sheet');
await page.waitForFunction(() => !document.querySelector('[role=progressbar]') && (document.querySelector('a[download]') || document.querySelector('.status.error')), null, { timeout: 300000 });
console.log('four-view in', Date.now() - t, 'ms |', await page.textContent('.status'));
const href = await page.getAttribute('a[download]', 'href');
const b64 = await page.evaluate(async (h) => { const b = await (await fetch(h)).blob(); return await new Promise((r) => { const fr = new FileReader(); fr.onload = () => r(String(fr.result).split(',')[1]); fr.readAsDataURL(b); }); }, href);
writeFileSync('test-results/fourview-gcode.png', Buffer.from(b64, 'base64'));
await browser.close();
